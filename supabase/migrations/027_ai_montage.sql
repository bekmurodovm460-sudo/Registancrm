-- AI yordamchi orqali montaj: suhbatga yuborilgan media va AI tuzgan montaj loyihalari
create table if not exists crm_ai_media (
  id bigint generated by default as identity primary key,
  tg_id bigint not null,
  kind text not null check (kind in ('photo', 'video')),
  file_id text not null,
  vision_file_id text,
  width int, height int, duration numeric, file_size bigint,
  created_at timestamptz not null default now()
);
create index if not exists crm_ai_media_tg on crm_ai_media (tg_id, created_at desc);
create table if not exists crm_ai_projects (
  id uuid primary key default gen_random_uuid(),
  tg_id bigint not null,
  plan jsonb not null,
  files jsonb not null,
  created_at timestamptz not null default now()
);
alter table crm_ai_media enable row level security;
alter table crm_ai_projects enable row level security;
revoke all on crm_ai_media, crm_ai_projects from anon, authenticated;
