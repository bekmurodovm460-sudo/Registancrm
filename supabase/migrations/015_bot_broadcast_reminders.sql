create or replace function public.crm_run_bot_jobs()
returns bigint language plpgsql security definer set search_path = public, extensions as $$
declare s text;
begin
  select value into s from public.crm_secrets where key = 'cron_secret';
  return net.http_post(
    url := 'https://bbnakgvgoydahagiwltn.supabase.co/functions/v1/bot-jobs',
    body := '{"action":"cron"}'::jsonb,
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-cron-secret', s),
    timeout_milliseconds := 120000
  );
end $$;
revoke all on function public.crm_run_bot_jobs() from public, anon, authenticated;

select cron.unschedule('crm-bot-jobs') where exists (select 1 from cron.job where jobname = 'crm-bot-jobs');
select cron.schedule('crm-bot-jobs', '*/10 * * * *', $$select public.crm_run_bot_jobs()$$);
