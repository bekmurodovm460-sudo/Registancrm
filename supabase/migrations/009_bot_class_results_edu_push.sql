-- Ismni solishtirish uchun normallashtirish: kichik harf, apostroflarsiz, so'zlar tartibi muhim emas
create or replace function public.crm_norm_name(p text)
returns text language sql immutable set search_path = public as $$
  select array_to_string(array(
    select w from unnest(string_to_array(
      trim(regexp_replace(translate(lower(coalesce(p, '')), 'ʻʼ‘’''`ʹ', ''), '\s+', ' ', 'g')), ' ')) w
    where w <> '' order by w), ' ');
$$;

-- Natijani yozish: sinfda o'quvchi topilsa yangilanadi, topilmasa qo'shiladi (faqat service role)
create or replace function public.crm_bot_record_result(
  p_school text, p_class text, p_name text, p_q1 int, p_q2 int, p_score numeric, p_test text)
returns table(student_id bigint, matched boolean, full_name text)
language plpgsql security definer set search_path = public as $$
declare
  sid bigint;
  nm text;
  key text := public.crm_norm_name(p_name);
begin
  select s.id, s.data->>'fullName' into sid, nm
  from public.crm_students s
  where s.school_id = p_school and s.class_name = p_class
    and public.crm_norm_name(s.data->>'fullName') = key
  order by s.id limit 1;

  if sid is not null then
    update public.crm_students
       set data = data || jsonb_build_object('q1', p_q1, 'q2', p_q2, 'score', p_score,
                                             'lastExam', jsonb_build_object('test', p_test, 'score', p_score, 'at', now()))
     where id = sid;
    return query select sid, true, nm;
  else
    sid := nextval('public.crm_bot_student_seq');
    nm := regexp_replace(trim(p_name), '\s+', ' ', 'g');
    insert into public.crm_students (id, data) values (sid, jsonb_build_object(
      'id', sid, 'fullName', nm, 'className', p_class, 'schoolId', p_school, 'phone', '',
      'q1', p_q1, 'q2', p_q2, 'score', p_score, 'callStatus', 'Raqamsiz', 'note', 'Telegram bot orqali qo‘shildi',
      'source', 'telegram-omr', 'lastExam', jsonb_build_object('test', p_test, 'score', p_score, 'at', now())));
    return query select sid, false, nm;
  end if;
end $$;
revoke all on function public.crm_bot_record_result(text, text, text, int, int, numeric, text) from public, anon, authenticated;

