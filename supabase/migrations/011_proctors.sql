-- Natija yozish: o'quvchi telefoni va ota-ona telefoni (ixtiyoriy) ham saqlanadi.
-- CRM'dagi `phone` — ota-ona telefoni (yutuqli karta shu raqam bilan olinadi), `studentPhone` — o'quvchiniki.
drop function if exists public.crm_bot_record_result(text, text, text, int, int, numeric, text);
create or replace function public.crm_bot_record_result(
  p_school text, p_class text, p_name text, p_q1 int, p_q2 int, p_score numeric, p_test text,
  p_student_phone text default null, p_parent_phone text default null)
returns table(student_id bigint, matched boolean, full_name text)
language plpgsql security definer set search_path = public as $$
declare
  sid bigint;
  nm text;
  key text := public.crm_norm_name(p_name);
  extra jsonb := '{}'::jsonb;
begin
  if coalesce(p_student_phone, '') <> '' then extra := extra || jsonb_build_object('studentPhone', p_student_phone); end if;
  if coalesce(p_parent_phone, '') <> '' then extra := extra || jsonb_build_object('phone', p_parent_phone); end if;

  select s.id, s.data->>'fullName' into sid, nm
  from public.crm_students s
  where s.school_id = p_school and s.class_name = p_class
    and public.crm_norm_name(s.data->>'fullName') = key
  order by s.id limit 1;

  if sid is not null then
    update public.crm_students
       set data = data || extra || jsonb_build_object('q1', p_q1, 'q2', p_q2, 'score', p_score,
             'lastExam', jsonb_build_object('test', p_test, 'score', p_score, 'at', now()))
             || case when coalesce(p_parent_phone, '') <> '' and coalesce(data->>'callStatus', '') = 'Raqamsiz'
                     then jsonb_build_object('callStatus', 'Yangi') else '{}'::jsonb end
     where id = sid;
    return query select sid, true, nm;
  else
    sid := nextval('public.crm_bot_student_seq');
    nm := regexp_replace(trim(p_name), '\s+', ' ', 'g');
    insert into public.crm_students (id, data) values (sid, jsonb_build_object(
      'id', sid, 'fullName', nm, 'className', p_class, 'schoolId', p_school, 'phone', coalesce(p_parent_phone, ''),
      'q1', p_q1, 'q2', p_q2, 'score', p_score,
      'callStatus', case when coalesce(p_parent_phone, '') <> '' then 'Yangi' else 'Raqamsiz' end,
      'note', 'Nazoratchi orqali qo‘shildi', 'source', 'proctor-omr',
      'lastExam', jsonb_build_object('test', p_test, 'score', p_score, 'at', now())) || extra);
    return query select sid, false, nm;
  end if;
end $$;
revoke all on function public.crm_bot_record_result(text, text, text, int, int, numeric, text, text, text) from public, anon, authenticated;

-- Maktabdagi sinf harflari (sinf raqami bo'yicha)
create or replace function public.crm_school_letters(p_school text, p_grade text)
returns table(class_name text, letter text)
language sql stable security definer set search_path = public as $$
  select name, regexp_replace(name, '^\s*\d+\s*-?\s*', '')
  from public.crm_classes
  where school_id = p_school and substring(name from '\d+') = p_grade
  order by name;
$$;
revoke all on function public.crm_school_letters(text, text) from public, anon, authenticated;

