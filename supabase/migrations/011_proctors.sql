-- Nazoratchilar va ustozlar: CRM'da kiritiladi, Telegram'da raqam orqali bog'lanadi.
-- Faqat ular maktab testlari natijasini (bot / Mini App) yubora oladi.

create table if not exists public.crm_proctors (
  id bigint generated by default as identity primary key,
  full_name text not null,
  phone text not null,
  phone_digits text generated always as (right(regexp_replace(phone, '\D', '', 'g'), 9)) stored,
  role text not null default 'nazoratchi' check (role in ('nazoratchi', 'ustoz')),
  school_id text,                 -- null = barcha maktablar
  active boolean not null default true,
  tg_user_id bigint,
  tg_username text,
  linked_at timestamptz,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid()
);
create unique index if not exists crm_proctors_phone_uidx on public.crm_proctors (phone_digits);
create index if not exists crm_proctors_tg_idx on public.crm_proctors (tg_user_id);

alter table public.crm_proctors enable row level security;
drop policy if exists crm_proctors_select on public.crm_proctors;
create policy crm_proctors_select on public.crm_proctors for select to authenticated
  using ((select public.crm_role()) in ('admin', 'operator'));
drop policy if exists crm_proctors_write on public.crm_proctors;
create policy crm_proctors_write on public.crm_proctors for all to authenticated
  using ((select public.crm_role()) = 'admin') with check ((select public.crm_role()) = 'admin');

