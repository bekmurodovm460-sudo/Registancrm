create table if not exists crm_edu_book_orders (
  id bigint generated by default as identity primary key,
  teacher_tg bigint not null,
  teacher_name text not null,
  employee_id text,
  subject text not null,
  group_name text,
  book text not null,
  qty int not null check (qty > 0 and qty <= 500),
  note text,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected', 'ready')),
  decided_by text,
  decided_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists crm_edu_book_orders_status on crm_edu_book_orders (status, created_at desc);
create index if not exists crm_edu_book_orders_teacher on crm_edu_book_orders (teacher_tg, created_at desc);
alter table crm_edu_book_orders enable row level security;
revoke all on crm_edu_book_orders from anon, authenticated;
grant select on crm_edu_book_orders to authenticated;
drop policy if exists crm_edu_book_orders_read on crm_edu_book_orders;
create policy crm_edu_book_orders_read on crm_edu_book_orders for select to authenticated using (crm_role() = 'admin');
