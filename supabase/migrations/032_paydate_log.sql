-- Edutizim "To'lov sanasi" ni ommaviy yangilash: har bir yozuvdan oldingi qiymat saqlanadi (kerak bo'lsa qaytarish uchun)
create table if not exists crm_edu_paydate_log (
  id bigint generated by default as identity primary key,
  run_id text not null,
  student_id text not null,
  full_name text,
  balance numeric,
  kind text,            -- past (balans 0 ga tushgan kun) | future (pul tugaydigan kun)
  old_date text,
  new_date text,
  ok boolean,
  error text,
  created_at timestamptz not null default now()
);
create index if not exists crm_edu_paydate_log_run on crm_edu_paydate_log (run_id, student_id);
alter table crm_edu_paydate_log enable row level security;
revoke all on crm_edu_paydate_log from anon, authenticated;
