-- Edutizim boti: rollar (top / service / teacher) va o'qituvchilarga vazifalar
create table if not exists public.crm_edu_bot_users (
  tg_id bigint primary key,
  role text not null default 'pending' check (role in ('pending','top','service','teacher','blocked')),
  full_name text,
  phone text,
  employee_id text,          -- Edutizim xodim (o'qituvchi) _id
  tg_username text,
  approved_by bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.crm_edu_bot_users enable row level security;
drop policy if exists crm_edu_bot_users_select on public.crm_edu_bot_users;
create policy crm_edu_bot_users_select on public.crm_edu_bot_users for select to authenticated
  using ((select public.crm_role()) in ('admin','operator'));

create table if not exists public.crm_edu_tasks (
  id bigint generated by default as identity primary key,
  kind text not null default 'archive',
  title text not null,
  teacher_tg bigint not null,
  teacher_name text,
  employee_id text,
  period_from timestamptz,
  period_to timestamptz,
  deadline timestamptz not null,
  items jsonb not null default '[]'::jsonb,   -- [{studentId,name,phone,group,leftAt,comment,doneAt}]
  status text not null default 'open' check (status in ('open','done','overdue','cancelled')),
  created_by bigint,
  last_reminded_at timestamptz,
  created_at timestamptz not null default now(),
  done_at timestamptz
);
alter table public.crm_edu_tasks enable row level security;
drop policy if exists crm_edu_tasks_select on public.crm_edu_tasks;
create policy crm_edu_tasks_select on public.crm_edu_tasks for select to authenticated
  using ((select public.crm_role()) in ('admin','operator'));
create index if not exists crm_edu_tasks_open on public.crm_edu_tasks (status, last_reminded_at);
