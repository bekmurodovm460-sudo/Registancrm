-- 📞 Call center: operator o'quvchi yuboradi (kurs, daraja, Globus guruhi) → menejer o'quvchi kelgach tasdiqlaydi →
-- Edutizimga menejer nomidan yoziladi → operatorga xabar; keyin aktivga o'tsa ham xabar (oylik samaradorlik)
create table if not exists public.crm_edu_call_requests (
  id bigint generated by default as identity primary key,
  caller_tg bigint not null,
  caller_name text,
  full_name text not null,
  phone text,
  course_id text,
  course_name text,
  level text,
  group_id text,
  group_name text,
  note text,
  status text not null default 'pending' check (status in ('pending', 'writing', 'added', 'rejected', 'failed')),
  manager_tg bigint,
  manager_name text,
  result text,
  edu_student_id text,
  edu_order_id text,
  created_at timestamptz not null default now(),
  decided_at timestamptz,
  active_at timestamptz,
  active_group text
);
create index if not exists crm_edu_call_requests_caller on public.crm_edu_call_requests (caller_tg, created_at desc);
create index if not exists crm_edu_call_requests_status on public.crm_edu_call_requests (status, created_at desc);
alter table public.crm_edu_call_requests enable row level security;
revoke all on public.crm_edu_call_requests from anon, authenticated;
