-- Edutizimga menejerning shaxsiy akkaunti nomidan yoziladi.
create table if not exists crm_edu_lead_requests (
  id bigint generated by default as identity primary key,
  kind text not null default 'lead' check (kind in ('lead', 'order')),
  full_name text not null,
  phone text,
  course_id text,
  course_name text,
  edu_student_id text,
  note text,
  created_by bigint not null,
  created_by_name text,
  manager_tg bigint not null,
  manager_name text,
  status text not null default 'pending' check (status in ('pending', 'writing', 'done', 'rejected', 'failed')),
  result text,
  edu_order_id text,
  created_at timestamptz not null default now(),
  decided_at timestamptz
);
create index if not exists crm_edu_lead_requests_mgr on crm_edu_lead_requests (manager_tg, status, created_at desc);
alter table crm_edu_lead_requests enable row level security;
revoke all on crm_edu_lead_requests from anon, authenticated;
