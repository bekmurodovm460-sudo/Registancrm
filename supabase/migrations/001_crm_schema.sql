-- =========================================================
-- 1. Profillar va rollar
-- =========================================================
create table if not exists public.crm_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text,
  role text not null default 'pending' check (role in ('admin','operator','teacher','pending')),
  class_name text,
  created_at timestamptz not null default now()
);

create or replace function public.crm_role()
returns text language sql stable security definer set search_path = public as $$
  select role from public.crm_profiles where id = auth.uid();
$$;

create or replace function public.crm_teacher_class()
returns text language sql stable security definer set search_path = public as $$
  select class_name from public.crm_profiles where id = auth.uid();
$$;

-- Yangi foydalanuvchi: birinchisi admin, qolganlari "pending" (admin tasdiqlaguncha hech narsa ko'rmaydi)
create or replace function public.crm_handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.crm_profiles (id, email, full_name, role)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1)),
    case when not exists (select 1 from public.crm_profiles where role = 'admin') then 'admin' else 'pending' end
  )
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists crm_on_auth_user_created on auth.users;
create trigger crm_on_auth_user_created
  after insert on auth.users
  for each row execute function public.crm_handle_new_user();

