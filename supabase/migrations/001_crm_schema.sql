-- 4. updated_at triggerlari
-- =========================================================
create or replace function public.crm_touch()
returns trigger language plpgsql set search_path = public as $$
begin
  new.updated_at := now();
  new.updated_by := auth.uid();
  return new;
end $$;

do $$
declare t text;
begin
  foreach t in array array['crm_classes','crm_students','crm_mock_students','crm_payments','crm_used_cards','crm_settings'] loop
    execute format('drop trigger if exists %I_touch on public.%I', t, t);
    execute format('create trigger %I_touch before insert or update on public.%I for each row execute function public.crm_touch()', t, t);
  end loop;
end $$;

