-- ID bloki: har chaqiruv 1000 talik yangi oraliq beradi (10000.. dan boshlab)
create or replace function public.crm_reserve_id_block()
returns bigint language plpgsql security definer set search_path = public as $$
begin
  if coalesce(public.crm_role(), '') not in ('admin','operator','teacher') then
    raise exception 'ruxsat yo''q';
  end if;
  return nextval('public.crm_id_block_seq') * 1000;
end $$;

-- Maxfiy kalitni yozish (faqat admin). Qiymat qaytarilmaydi.
create or replace function public.crm_set_secret(p_key text, p_value text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if coalesce(public.crm_role(), '') <> 'admin' then raise exception 'faqat admin'; end if;
  if p_key not in ('telegram_bot_token','telegram_admin_chat_id','edutizim_base_url','edutizim_login','edutizim_password') then
    raise exception 'noma''lum kalit';
  end if;
  if coalesce(p_value,'') = '' then
    delete from public.crm_secrets where key = p_key;
  else
    insert into public.crm_secrets(key, value) values (p_key, p_value)
    on conflict (key) do update set value = excluded.value, updated_at = now();
  end if;
end $$;

-- Qaysi kalitlar o'rnatilganini ko'rsatadi (qiymatsiz)
create or replace function public.crm_secret_status()
returns table(key text, is_set boolean, updated_at timestamptz)
language plpgsql security definer set search_path = public as $$
begin
  if coalesce(public.crm_role(), '') <> 'admin' then raise exception 'faqat admin'; end if;
  return query select s.key, true, s.updated_at from public.crm_secrets s;
end $$;

-- Ota-ona portali (loginsiz): ism (kamida 4 belgi) yoki to'liq telefon raqami bo'yicha
create or replace function public.crm_parent_lookup(p_query text)
returns table(id bigint, full_name text, class_name text, score numeric, grade_key text, rank bigint, total bigint)
language sql stable security definer set search_path = public as $$
  with q as (
    select lower(trim(p_query)) as t, regexp_replace(p_query, '\D', '', 'g') as digits
  ),
  ranked as (
    select s.id,
           s.data->>'fullName' as full_name,
           s.class_name,
           coalesce((s.data->>'score')::numeric, 0) as score,
           coalesce(substring(s.class_name from '\d+') || '-sinflar', 'Boshqa sinflar') as grade_key,
           regexp_replace(coalesce(s.data->>'phone',''), '\D', '', 'g') as phone_digits,
           row_number() over (partition by coalesce(substring(s.class_name from '\d+'), 'x')
                              order by coalesce((s.data->>'score')::numeric, 0) desc) as rank,
           count(*) over (partition by coalesce(substring(s.class_name from '\d+'), 'x')) as total
    from public.crm_students s
  )
  select r.id, r.full_name, r.class_name, r.score, r.grade_key, r.rank, r.total
  from ranked r, q
  where (length(q.t) >= 4 and lower(r.full_name) like '%' || q.t || '%')
     or (length(q.digits) >= 9 and r.phone_digits like '%' || right(q.digits, 9))
  order by r.full_name
  limit 10;
$$;

revoke all on function public.crm_parent_lookup(text) from public;
grant execute on function public.crm_parent_lookup(text) to anon, authenticated;
revoke all on function public.crm_set_secret(text, text) from public, anon;
grant execute on function public.crm_set_secret(text, text) to authenticated;
revoke all on function public.crm_secret_status() from public, anon;
grant execute on function public.crm_secret_status() to authenticated;
