  using ((select public.crm_role()) = 'admin' and id <> (select auth.uid()));

-- Umumiy CRM jadvallari: o'qish — tasdiqlangan rollar; yozish — admin/operator; o'chirish — admin
do $$
declare t text;
begin
  foreach t in array array['crm_classes','crm_students','crm_mock_students','crm_payments','crm_used_cards','crm_tests','crm_omr_submissions','crm_mock_registrations'] loop
    execute format('drop policy if exists %I_select on public.%I', t, t);
    execute format($p$create policy %I_select on public.%I for select to authenticated
      using ((select public.crm_role()) in ('admin','operator','teacher'))$p$, t, t);
    execute format('drop policy if exists %I_insert on public.%I', t, t);
    execute format($p$create policy %I_insert on public.%I for insert to authenticated
      with check ((select public.crm_role()) in ('admin','operator'))$p$, t, t);
    execute format('drop policy if exists %I_update on public.%I', t, t);
    execute format($p$create policy %I_update on public.%I for update to authenticated
      using ((select public.crm_role()) in ('admin','operator'))
      with check ((select public.crm_role()) in ('admin','operator'))$p$, t, t);
    execute format('drop policy if exists %I_delete on public.%I', t, t);
    execute format($p$create policy %I_delete on public.%I for delete to authenticated
      using ((select public.crm_role()) = 'admin')$p$, t, t);
  end loop;
end $$;

