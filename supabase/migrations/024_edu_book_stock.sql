-- Moliya boti: kitoblar ombori (qoldiq + harakatlar tarixi)
create table if not exists crm_edu_book_stock (
  id bigint generated by default as identity primary key,
  subject text not null,
  title text not null,
  qty int not null default 0,
  min_qty int not null default 5,
  updated_at timestamptz not null default now(),
  unique (subject, title)
);
create table if not exists crm_edu_book_moves (
  id bigint generated by default as identity primary key,
  book_id bigint not null references crm_edu_book_stock(id) on delete cascade,
  delta int not null,
  kind text not null check (kind in ('in', 'out', 'adjust', 'order')),
  order_id bigint,
  qty_after int not null,
  note text,
  by_name text,
  created_at timestamptz not null default now()
);
create index if not exists crm_edu_book_moves_book on crm_edu_book_moves (book_id, created_at desc);
alter table crm_edu_book_stock enable row level security;
alter table crm_edu_book_moves enable row level security;
revoke all on crm_edu_book_stock, crm_edu_book_moves from anon, authenticated;

-- Atomik harakat: qoldiqni o'zgartiradi va tarixga yozadi. p_set — inventarizatsiya (aniq son)
create or replace function crm_book_stock_move(p_book bigint, p_delta int, p_kind text, p_order bigint default null, p_note text default null, p_by text default null, p_set int default null)
returns int language plpgsql security definer set search_path = public as $$
declare cur int; nxt int;
begin
  select qty into cur from crm_edu_book_stock where id = p_book for update;
  if cur is null then raise exception 'Kitob topilmadi'; end if;
  nxt := coalesce(p_set, cur + p_delta);
  if nxt < 0 then raise exception 'Omborda yetarli emas: % ta bor', cur; end if;
  update crm_edu_book_stock set qty = nxt, updated_at = now() where id = p_book;
  insert into crm_edu_book_moves (book_id, delta, kind, order_id, qty_after, note, by_name) values (p_book, nxt - cur, p_kind, p_order, nxt, p_note, p_by);
  return nxt;
end $$;
revoke all on function crm_book_stock_move(bigint, int, text, bigint, text, text, int) from public, anon, authenticated;
