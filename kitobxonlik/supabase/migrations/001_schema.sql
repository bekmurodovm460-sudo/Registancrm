-- To'lov tasdiqlanganda a'zolik muddati uzaytiriladi
create or replace function public.ka_payment_apply()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.status = 'Tasdiqlandi' and (tg_op = 'INSERT' or old.status is distinct from 'Tasdiqlandi') then
    update public.ka_members
       set paid_until = greatest(coalesce(paid_until, now()), now()) + make_interval(days => new.days)
     where id = new.member_id;
    new.approved_at := now();
    new.approved_by := coalesce(auth.uid(), new.approved_by);
  elsif tg_op = 'UPDATE' and old.status = 'Tasdiqlandi' and new.status <> 'Tasdiqlandi' then
    update public.ka_members set paid_until = paid_until - make_interval(days => old.days) where id = new.member_id;
  end if;
  return new;
end $$;
drop trigger if exists ka_payments_apply on public.ka_payments;
create trigger ka_payments_apply before insert or update on public.ka_payments
  for each row execute function public.ka_payment_apply();

