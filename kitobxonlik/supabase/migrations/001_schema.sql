-- Ball: kitob = round(test%/10) + audio baho (maks. 20); tanlov = 30/20/10 (TOP-3) + test%/10
create or replace function public.ka_leaderboard(p_period text default 'all', p_limit int default 20)
returns table(rank bigint, member_id bigint, full_name text, city text, points numeric, books bigint, contests bigint)
language plpgsql stable security definer set search_path = public as $$
#variable_conflict use_column
declare since timestamptz := case p_period
  when 'week' then date_trunc('week', now())
  when 'month' then date_trunc('month', now())
  else '-infinity'::timestamptz end;
begin
  if auth.role() = 'authenticated' and not public.ka_is(array['admin','moderator','kassir']) then
    raise exception 'ruxsat yo''q';
  end if;
  return query
  select row_number() over (order by sum(c.points) desc, count(*) desc, min(m.full_name)) as rk,
         m.id, m.full_name, m.city, sum(c.points),
         count(*) filter (where c.kind = 'book'), count(*) filter (where c.kind = 'contest')
  from public.ka_completions c join public.ka_members m on m.id = c.member_id
  where c.created_at >= since and m.status = 'active'
  group by m.id
  order by rk
  limit greatest(1, least(coalesce(p_limit, 20), 200));
end $$;
revoke all on function public.ka_leaderboard(text, int) from public, anon;
grant execute on function public.ka_leaderboard(text, int) to authenticated;

create or replace function public.ka_dashboard()
returns jsonb language plpgsql stable security definer set search_path = public as $$
begin
  if not public.ka_is(array['admin','moderator','kassir']) then raise exception 'ruxsat yo''q'; end if;
  return jsonb_build_object(
    'members', (select count(*) from public.ka_members),
    'members_week', (select count(*) from public.ka_members where created_at >= now() - interval '7 days'),
    'paid', (select count(*) from public.ka_members where paid_until > now()),
    'books', (select count(*) from public.ka_books where active),
    'opens', (select count(*) from public.ka_book_opens),
    'attempts', (select count(*) from public.ka_attempts where status = 'done'),
    'passed', (select count(*) from public.ka_attempts where status = 'done' and passed),
    'reviews_new', (select count(*) from public.ka_reviews where status = 'Yangi'),
    'completions', (select count(*) from public.ka_completions where kind = 'book'),
    'groups', (select count(*) from public.ka_groups where active),
    'payments_pending', (select count(*) from public.ka_payments where status = 'Kutilmoqda'),
    'revenue_month', (select coalesce(sum(amount), 0) from public.ka_payments where status = 'Tasdiqlandi' and created_at >= date_trunc('month', now())),
    'meetings_next', (select count(*) from public.ka_meetings where starts_at >= now())
  );
end $$;
revoke all on function public.ka_dashboard() from public, anon;
grant execute on function public.ka_dashboard() to authenticated;

