returns text language plpgsql security definer set search_path = public as $$
declare c text := upper(substr(md5(random()::text), 1, 8));
begin
  if not public.ka_is(array['admin','moderator','kassir']) then raise exception 'ruxsat yo''q'; end if;
  update public.ka_staff set link_code = c where id = auth.uid();
  return c;
end $$;
revoke all on function public.ka_new_link_code() from public, anon;
grant execute on function public.ka_new_link_code() to authenticated;

revoke all on function public.ka_set_secret(text, text) from public, anon;
grant execute on function public.ka_set_secret(text, text) to authenticated;
revoke all on function public.ka_secret_status() from public, anon;
grant execute on function public.ka_secret_status() to authenticated;
revoke all on function public.ka_next_cert() from public, anon, authenticated;
revoke all on function public.ka_handle_new_user() from public, anon, authenticated;

