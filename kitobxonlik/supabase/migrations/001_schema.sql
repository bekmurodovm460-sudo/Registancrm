create or replace function public.ka_set_secret(p_key text, p_value text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.ka_is(array['admin']) then raise exception 'faqat admin'; end if;
  if p_key not in ('telegram_bot_token', 'telegram_admin_chat_id') then raise exception 'noma''lum kalit'; end if;
  if coalesce(p_value, '') = '' then delete from public.ka_secrets where key = p_key;
  else insert into public.ka_secrets(key, value) values (p_key, p_value)
       on conflict (key) do update set value = excluded.value, updated_at = now();
  end if;
end $$;

create or replace function public.ka_secret_status()
returns table(key text, is_set boolean, updated_at timestamptz)
language plpgsql security definer set search_path = public as $$
begin
  if not public.ka_is(array['admin']) then raise exception 'faqat admin'; end if;
  return query select s.key, true, s.updated_at from public.ka_secrets s where s.key <> 'cron_secret' and s.key <> 'functions_url';
end $$;

